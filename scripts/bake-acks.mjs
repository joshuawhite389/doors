// Bake the Agent's acknowledgement lines (public/lib/ack.js) as Aura-2 MP3s under public/audio/ack/, through a dev
// server that has Workers AI (WORKERS_AI=1 node scripts/dev.mjs <port>). One call a line (a dozen, ~30 characters each:
// ~1,000 neurons in all); a line whose clip exists is skipped unless --force. The clip must come from the Aura-2
// voice (x-doors-voice), never MeloTTS: when the day's neurons are low it stops and says so.
// Usage: node scripts/bake-acks.mjs <base-url> [--force]
import fs from "node:fs";
import { ACKS, ackPath } from "../public/lib/ack.js";

const [base, flag] = process.argv.slice(2);
if (!base) { console.error("usage: node scripts/bake-acks.mjs <base-url> [--force]"); process.exit(2); }
const force = flag === "--force";
fs.mkdirSync(new URL("../public/audio/ack/", import.meta.url), { recursive: true });
let made = 0;
for (const a of Object.values(ACKS).flat()) {
  const file = new URL(`../public${ackPath(a.id)}`, import.meta.url);
  if (!force && fs.existsSync(file)) { console.log(`keep ${a.id}`); continue; }
  const r = await fetch(`${base}/api/voice/say`, { method: "POST", headers: { "content-type": "application/json", origin: base }, body: JSON.stringify({ text: a.text }) });
  const voice = r.headers.get("x-doors-voice");
  if (!r.ok || !/^audio\//.test(r.headers.get("content-type") ?? "")) { console.error(`${a.id}: ${r.status} ${await r.text()}`); process.exit(1); }
  if (voice === "melotts") { console.error(`${a.id}: the server read it with MeloTTS (neurons low): stopping`); process.exit(1); }
  const bytes = Buffer.from(await r.arrayBuffer());
  fs.writeFileSync(file, bytes);
  made++;
  console.log(`made ${a.id} (${voice}, ${bytes.length} B): ${a.text}`);
}
console.log(`${made} clips made`);
// the phone bundles the same clips (app-mobile/src/ack-files.ts → assets/audio/ack/)
const appDir = new URL("../app-mobile/assets/audio/ack/", import.meta.url);
fs.mkdirSync(appDir, { recursive: true });
const ids = Object.values(ACKS).flat().map((a) => a.id);
for (const id of ids) fs.copyFileSync(new URL(`../public${ackPath(id)}`, import.meta.url), new URL(`${id}.mp3`, appDir));
fs.writeFileSync(new URL("../app-mobile/src/ack-files.ts", import.meta.url), `// Generated by scripts/bake-acks.mjs from public/lib/ack.js and public/audio/ack/. Don't edit by hand.\n// The Doors Agent's acknowledgement clips (Aura-2), bundled so they play at once with no network.\nexport const ACK_FILES: Record<string, number> = {\n${ids.map((id) => `  "${id}": require("../assets/audio/ack/${id}.mp3"),\n`).join("")}};\n`);
console.log(`app-mobile: ${ids.length} clips copied, src/ack-files.ts written`);
