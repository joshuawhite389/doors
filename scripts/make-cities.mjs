// Builds public/lib/us-cities.js: every US incorporated place (and Urban Honolulu, the census's Honolulu) of 20,000 people or more, as
// [name, state, lat, lon, population], for the city field's autocomplete (public/lib/citylist.js). No Qloo, no network
// at run time. Sources, both US Census Bureau (public domain), downloaded once into <dir>:
//   sub-est2024.csv  population estimates, July 2024 (www2.census.gov/programs-surveys/popest/datasets/2020-2024/cities/totals/)
//   2024_Gaz_place_national.txt  Gazetteer places: internal point lat/lon (www2.census.gov/geo/docs/maps-data/data/gazetteer/2024_Gazetteer/)
// Usage: node scripts/make-cities.mjs <dir> [minPop=20000]
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = process.argv[2];
if (!dir) throw new Error("usage: node scripts/make-cities.mjs <dir with sub-est2024.csv and 2024_Gaz_place_national.txt> [minPop]");
const MIN = Number(process.argv[3] ?? 20000);

// Gazetteer: GEOID (state FIPS + place) → [USPS state, lat, lon]
const gaz = new Map();
for (const line of readFileSync(join(dir, "2024_Gaz_place_national.txt"), "latin1").split("\n").slice(1)) {
  const f = line.split("\t");
  if (f.length < 12) continue;
  gaz.set(f[1], [f[0], Number(f[10]), Number(f[11])]);
}

// The legal name minus its kind ("Cincinnati city" → "Cincinnati"); consolidated governments by their everyday name.
const COMMON = { "Athens-Clarke County": "Athens", "Augusta-Richmond County": "Augusta", "Macon-Bibb County": "Macon", "Urban Honolulu": "Honolulu",
  "Lexington-Fayette": "Lexington", "Louisville/Jefferson County": "Louisville", "Butte-Silver Bow": "Butte", "Nashville-Davidson": "Nashville",
  "Boise City": "Boise", "San Buenaventura (Ventura)": "Ventura", "El Paso de Robles (Paso Robles)": "Paso Robles" };
const KIND = / (city|town|village|borough|municipality|CDP|metro township|township|urban county|unified government|consolidated government|metropolitan government|metro government|city and borough|corporation|plantation)$/;
const clean = (n) => { const s = n.replace(/ \(balance\)$/, "").replace(KIND, ""); return COMMON[s] ?? s; };

const rows = [];
const csv = readFileSync(join(dir, "sub-est2024.csv"), "latin1").split("\n");
const head = csv[0].split(",");
const col = (k) => head.indexOf(k);
const [SUM, ST, PL, NAME, POP] = ["SUMLEV", "STATE", "PLACE", "NAME", "POPESTIMATE2024"].map(col);
for (const line of csv.slice(1)) {
  const f = line.split(",");
  if (f[SUM] !== "162" || Number(f[POP]) < MIN) continue; // 162: an incorporated place, counted once
  const g = gaz.get(f[ST] + f[PL]);
  if (!g) { console.warn(`no gazetteer point for ${f[NAME]} (${f[ST]}${f[PL]})`); continue; }
  rows.push([clean(f[NAME]), g[0], +g[1].toFixed(4), +g[2].toFixed(4), Number(f[POP])]);
}
rows.sort((a, b) => b[4] - a[4] || a[0].localeCompare(b[0]));
const odd = rows.filter((r) => /[^A-Za-z .'\-ñéèáóíüÑ]/.test(r[0]) || /\b(County|government)\b/.test(r[0]));
if (odd.length) console.warn("check these names:", odd.map((r) => `${r[0]}, ${r[1]}`).join("; "));
const out = `// US cities of ${MIN.toLocaleString("en-US")}+ people: [name, state, lat, lon, population 2024], by population. Generated by
// scripts/make-cities.mjs from US Census Bureau data (public domain): Vintage 2024 population estimates and the 2024
// Gazetteer places file. Do not edit by hand.
export const US_CITIES = [
${rows.map((r) => JSON.stringify(r)).join(",\n")}
];
`;
writeFileSync(new URL("../public/lib/us-cities.js", import.meta.url), out);
console.log(`${rows.length} cities ≥ ${MIN} → public/lib/us-cities.js (${(out.length / 1024).toFixed(0)} KB)`);
