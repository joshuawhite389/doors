// qloofull (Jard 10-27): the baked BASELINE a live door's enrichment record is compared with (public/lib/enrich.js
// vsBaseline), so a door in a city with no baked file still gets its distinctive Qloo lines (talking points, Agent, deep
// facts) instead of vsCity: null. Counts over every door with basis "door" in the full records of every city Doors has
// read (data/enrich/<city>.json, private, tracked), names counted once dropped (compact: the lift reads the same).
//   node scripts/enrich-baseline.mjs            writes src/enrich-baseline.js (no call)
// Re-run after any enrich bake (scripts/enrich-bake.mjs). The Worker imports it; the page never loads it.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { baselineOf } from "../public/lib/enrich.js";

const ROOT = new URL("..", import.meta.url).pathname;
const DIR = join(ROOT, "data/enrich");
const doors = {};
const cities = [];
for (const f of readdirSync(DIR).filter((x) => x.endsWith(".json")).sort()) {
  const j = JSON.parse(readFileSync(join(DIR, f), "utf8"));
  let n = 0;
  for (const [id, r] of Object.entries(j.doors ?? {})) if (r?.qloo?.basis === "door" && !doors[id]) (doors[id] = r), n++;
  if (n) cities.push(f.replace(/\.json$/, ""));
}
const base = baselineOf(doors, { compact: true });
const out = { ...base, cities, baked: new Date().toISOString().slice(0, 10) };
const js = `// GENERATED by scripts/enrich-baseline.mjs from data/enrich/*.json (${out.baked}): do not edit. The baseline a live door's\n// enrichment record is compared with (src/worker.js /api/enrich → public/lib/enrich.js vsBaseline): ${base.n} doors Qloo\n// takes as a signal across ${cities.length} cities (${cities.join(", ")}). Names counted once are left out (the lift is the same).\nexport const ENRICH_BASELINE = ${JSON.stringify(out)};\n`;
writeFileSync(join(ROOT, "src/enrich-baseline.js"), js);
console.log(`enrich-baseline: ${base.n} doors, ${cities.length} cities, ${Object.keys(base.drinkCount).length} drink names, ${Object.keys(base.brandCount).length} brand names → src/enrich-baseline.js (${Math.round(js.length / 1024)} KB)`);
