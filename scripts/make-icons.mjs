// The phone's icons from the web's (public/lib/icons.js, one source): each icon → app-mobile/assets/icons/<name>.png,
// @2x, @3x (24/48/72 px, black on clear; the app tints them: app-mobile/src/icons.tsx), and the require() map
// app-mobile/src/icon-files.ts (Metro needs a literal require per file). Needs rsvg-convert (librsvg).
// node scripts/make-icons.mjs
import { execFileSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { ICONS, icon } from "../public/lib/icons.js";

const root = new URL("../app-mobile/", import.meta.url).pathname;
const out = `${root}assets/icons/`;
mkdirSync(out, { recursive: true });
const names = Object.keys(ICONS);
for (const n of names) {
  const svg = `<?xml version="1.0"?>${icon(n, 24).replace("<svg ", '<svg xmlns="http://www.w3.org/2000/svg" color="#000" ')}`;
  for (const [k, px] of [["", 24], ["@2x", 48], ["@3x", 72]]) {
    execFileSync("rsvg-convert", ["-w", String(px), "-h", String(px), "-o", `${out}${n}${k}.png`], { input: svg });
  }
}
writeFileSync(`${root}src/icon-files.ts`, `// Generated by scripts/make-icons.mjs from public/lib/icons.js. Don't edit by hand.\nexport const ICON_FILES = {\n${names.map((n) => `  ${n}: require("../assets/icons/${n}.png"),`).join("\n")}\n} as const;\nexport type IconName = keyof typeof ICON_FILES;\n`);
console.log(`${names.length} icons → ${out}`);
