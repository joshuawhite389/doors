// The trade persona brief (spec §3.1) → src/agent-brief/trade-brief.js, a string module the Worker imports (a Worker
// can't read files). Source: hackathons/qloo/agent/TRADE-BRIEF.md, copied to
// src/agent-brief/TRADE-BRIEF.md. Usage: node scripts/build-trade-brief.mjs [path/to/TRADE-BRIEF.md]
// (test/agent-core.test.mjs fails when the module and the copy differ.)
import { readFileSync, writeFileSync, copyFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
const dir = fileURLToPath(new URL("../src/agent-brief/", import.meta.url));
if (process.argv[2]) copyFileSync(process.argv[2], `${dir}TRADE-BRIEF.md`);
const md = readFileSync(`${dir}TRADE-BRIEF.md`, "utf8").trim();
writeFileSync(`${dir}trade-brief.js`, `// GENERATED by scripts/build-trade-brief.mjs from TRADE-BRIEF.md: edit the markdown, then re-run it.\nexport const TRADE_BRIEF = ${JSON.stringify(md)};\n`);
console.log(`trade-brief.js: ${md.length} chars`);
